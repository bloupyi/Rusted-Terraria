#!/usr/bin/env python3
"""Writes crates/world/src/tile_draw.rs from the local decompiled sources.

Only numbers come out: for each tile type, the size, vertical offset and
mirroring the game draws its cells with, and the frame or column conditions
they depend on. Animated frames and glow masks are left out. No code is copied.
Usage: tools/gen_tile_draw.py .local/terraria/<id>/sources
"""

import re
import sys
from pathlib import Path

OPS = {"==": "Eq", "!=": "Ne", "<": "Lt", "<=": "Le", ">": "Gt", ">=": "Ge"}
NEGATE = {"==": "!=", "!=": "==", ">=": "<", "<": ">=", "<=": ">", ">": "<="}
COND = re.compile(r"^(tileFrameX|tileFrameY|x)(?: ([%/]) (\d+))? (==|!=|<=|>=|<|>) (\d+)$")
FIELDS = {"tileFrameX": "X", "tileFrameY": "Y", "x": "Col"}


def cases(src):
    """Top-level cases of the first type switch: (labels, body lines)."""
    lines = src[src.index("private void GetTileDrawData("):].split("\n")
    start = next(i for i, l in enumerate(lines) if l == "\t\tswitch (typeCache)")
    groups, labels, body = [], [], []
    for i in range(start + 2, len(lines)):
        raw = lines[i]
        if re.match(r"^\t\t(case \d+:|default:)$", raw):
            if body:
                groups.append((labels, body))
                labels, body = [], []
            m = re.match(r"^\t\tcase (\d+):$", raw)
            if m:
                labels.append(int(m.group(1)))
        elif raw in ("\t\t{", "\t\t}"):
            nxt = lines[i + 1]
            if raw == "\t\t}" and not re.match(r"^\t\t(case \d+:|default:|})$", nxt):
                if labels:
                    groups.append((labels, body))
                return groups
        elif labels:
            body.append(raw)
    return groups


def cond(text, negate=False):
    """Simple conditions joined by &&, as (field, op, div, rem, value); None if unsupported."""
    parts = text.split(" && ")
    if negate and len(parts) > 1:
        return None
    out = []
    for p in parts:
        m = COND.match(p)
        if not m:
            return None
        f, kind, k, op, v = m.groups()
        if negate:
            op = NEGATE[op]
        div = int(k) if kind == "/" else 1
        rem = int(k) if kind == "%" else 0
        if f == "x" and rem == 0:
            return None
        out.append((FIELDS[f], op, div, rem, int(v)))
    return out


def block(lines, i):
    """Lines of the braced block starting at lines[i] == '{', and the index after it."""
    depth, j = 0, i
    while True:
        s = lines[j].strip()
        depth += s == "{"
        depth -= s == "}"
        j += 1
        if depth == 0:
            return lines[i + 1 : j - 1], j


def steps(lines, guard):
    out, i = [], 0
    while i < len(lines):
        s = lines[i].strip()
        m = re.match(r"^(?:else )?if \((.*)\)$", s)
        if m or s.startswith("switch") or s == "{":
            if s.startswith("switch") or s == "{":
                _, i = block(lines, i + (s != "{"))
                continue
            # An if / else if / else chain: each branch also needs the earlier ones false.
            earlier = []
            text = m.group(1)
            while True:
                body, i = block(lines, i + 1)
                c = cond(text)
                if c is not None and earlier is not None:
                    out += steps(body, guard + earlier + c)
                neg = cond(text, negate=True)
                earlier = None if neg is None or earlier is None else earlier + neg
                nxt = lines[i].strip() if i < len(lines) else ""
                m = re.match(r"^else if \((.*)\)$", nxt)
                if m:
                    text = m.group(1)
                    continue
                if nxt == "else":
                    body, i = block(lines, i + 1)
                    if earlier is not None:
                        out += steps(body, guard + earlier)
                break
            continue
        m = re.match(r"^tile(Width|Height|Top) (=|\+=|-=) (-?\d+);$", s)
        if m:
            k, op, v = m.groups()
            v = int(v) * (-1 if op == "-=" else 1)
            kind = {"Width": "W", "Height": "H"}.get(k, "Top" if op == "=" else "TopAdd")
            out.append((guard, kind, v))
        elif s == "tileSpriteEffect = (SpriteEffects)1;":
            out.append((guard, "Flip", 0))
        elif s == "break;" and not guard:
            break
        i += 1
    return out


def main():
    src = (Path(sys.argv[1]) / "Terraria.GameContent.Drawing/TileDrawing.cs").read_text()
    src = "\n".join(l for l in src.split("\n") if not l.strip().startswith("//IL_"))
    rules = []
    for labels, body in cases(src):
        st = steps(body, [])
        if st:
            rules += [(t, st) for t in labels]
    rules.sort(key=lambda r: r[0])
    out = [
        "//! Tile draw sizes, generated by tools/gen_tile_draw.py from the local",
        "//! decompilation of the player's own game. Do not edit by hand.",
        "",
        "use crate::draw::{Field::*, Op::*, Set::*, Step};",
        "",
        "/// Per tile type with a non-default draw, sorted by type: steps applied in order.",
        f"pub const RULES: [(u16, &[Step]); {len(rules)}] = [",
    ]
    for t, st in rules:
        parts = []
        for guard, kind, v in st:
            g = ", ".join(f"({f}, {OPS[op]}, {div}, {rem}, {val})" for f, op, div, rem, val in guard)
            s = "Flip" if kind == "Flip" else f"{kind}({v})"
            parts.append(f"Step {{ when: &[{g}], set: {s} }}")
        out.append(f"    ({t}, &[{', '.join(parts)}]),")
    out += ["];", ""]
    open(Path(__file__).parent.parent / "crates/world/src/tile_draw.rs", "w").write("\n".join(out))
    print(len(rules), "tile rules")


if __name__ == "__main__":
    main()

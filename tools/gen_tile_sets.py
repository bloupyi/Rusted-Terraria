#!/usr/bin/env python3
"""Writes crates/world/src/tile_sets.rs from the local decompiled sources.

Only tile ID lists come out (which types are solid, merge with dirt, ...):
no code. Usage: tools/gen_tile_sets.py .local/terraria/<id>/sources
"""

import re
import sys
from pathlib import Path

COUNT_RE = re.compile(r"ushort Count = (\d+);")
FLAGS = {
    "tileSolid": "SOLID",
    "tileSolidTop": "SOLID_TOP",
    "tileBrick": "BRICK",
    "tileStone": "STONE",
    "tileMoss": "MOSS",
    "tileMergeDirt": "MERGE_DIRT",
    "tileBlockLight": "BLOCK_LIGHT",
}
# Integer arrays split into one set per value.
LEVELS = {"tileLargeFrames": "LARGE_FRAMES", "wallLargeFrames": "WALL_LARGE_FRAMES"}
SETS = {
    "Platforms": "PLATFORMS",
    "tileMossBrick": "MOSS_BRICK",
    "ChecksForMerge": "CHECKS_FOR_MERGE",
    "ForcedDirtMerging": "FORCED_DIRT_MERGING",
    "Ore": "ORE",
    "TruncatesWalls": "TRUNCATES_WALLS",
}
CONVERSION = {"Grass": "GRASS", "MergesWithDirtInASpecialWay": "DIRT_SPECIAL"}


def method(src, name):
    start = src.index(f"static void {name}()")
    end = src.index("\n\t}\n", start)
    return src[start:end].split("\n")


def run(lines, values):
    i = 0
    while i < len(lines):
        line = lines[i].strip()
        m = re.match(r"for \((?:int|ushort) (\w+) = (\d+); \1 (<=|<) (\d+); \1\+\+\)", line)
        if m:
            var, lo, op, hi = m.group(1), int(m.group(2)), m.group(3), int(m.group(4))
            depth, body = 0, []
            i += 1
            while True:
                s = lines[i].strip()
                depth += s == "{"
                depth -= s == "}"
                if depth == 0 and s == "}":
                    break
                if depth == 1:
                    body.append(s)
                i += 1
            for n in range(lo, hi + (op == "<=")):
                for s in body:
                    assign(s, values, var, n)
        else:
            assign(line, values)
        i += 1


def assign(line, values, var=None, n=None):
    m = re.match(r"(?:Main\.)?(\w+)\[(\w+)\] = (true|false|\d+);", line)
    if not m or (m.group(1) not in FLAGS and m.group(1) not in LEVELS):
        return
    idx = m.group(2)
    idx = n if idx == var else int(idx) if idx.isdigit() else None
    if idx is not None:
        values.setdefault(m.group(1), {})[idx] = m.group(3)


def bool_set(text, name):
    m = re.search(rf"public static bool\[\] {name} = Factory\.CreateBoolSet\(([^)]*)\);", text)
    args = [a.strip() for a in m.group(1).split(",") if a.strip()]
    if args and args[0] in ("true", "false"):
        args = args[1:]
    return sorted(int(a) for a in args)


def main():
    src = Path(sys.argv[1])
    main_cs = (src / "Terraria/Main.cs").read_text()
    tile_id = (src / "Terraria.ID/TileID.cs").read_text()
    count = int(COUNT_RE.search(tile_id).group(1))
    values = {}
    run(method(main_cs, "Initialize_TileAndNPCData1"), values)
    run(method(main_cs, "Initialize_TileAndNPCData2"), values)
    lists = {}
    for field, name in FLAGS.items():
        lists[name] = sorted(k for k, v in values.get(field, {}).items() if v == "true")
    for field, name in LEVELS.items():
        for level in (1, 2):
            lists[f"{name}_{level}"] = sorted(k for k, v in values.get(field, {}).items() if v == str(level))
    sets_text = tile_id[tile_id.index("public static class Sets"):]
    conv = sets_text[sets_text.index("public static class Conversion"):]
    for field, name in SETS.items():
        lists[name] = bool_set(sets_text, field)
    for field, name in CONVERSION.items():
        lists[name] = bool_set(conv, field)
    out = [
        "//! Tile type sets, generated by tools/gen_tile_sets.py from the local",
        "//! decompilation of the player's own game. Do not edit by hand.",
        "",
        f"pub const COUNT: usize = {count};",
        "",
    ]
    for name, ids in lists.items():
        out.append(f"pub const {name}: TileSet = TileSet::of(&{ids});")
    out.append("")
    open(Path(__file__).parent.parent / "crates/world/src/tile_sets.rs", "w").write(
        "\n".join(out) + TAIL)
    print({k: len(v) for k, v in lists.items()})


TAIL = """
/// One bit per tile type.
#[derive(Clone, Copy)]
pub struct TileSet([u64; COUNT.div_ceil(64)]);

impl TileSet {
    pub const fn of(ids: &[u16]) -> Self {
        let mut bits = [0u64; COUNT.div_ceil(64)];
        let mut i = 0;
        while i < ids.len() {
            bits[ids[i] as usize / 64] |= 1 << (ids[i] % 64);
            i += 1;
        }
        Self(bits)
    }

    #[inline]
    pub fn has(&self, t: u16) -> bool {
        (t as usize) < COUNT && self.0[t as usize / 64] & (1 << (t % 64)) != 0
    }
}
"""

if __name__ == "__main__":
    main()

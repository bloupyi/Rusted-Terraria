#!/usr/bin/env python3
"""Writes crates/world/src/tile_light.rs from the local decompiled sources.

Only numbers come out: the light colour of each tile type that always glows
the same, and the colour of each torch style. Types whose light depends on
their frame or on the time are left to world::light. No code is copied.
Usage: tools/gen_tile_light.py .local/terraria/<id>/sources
"""

import re
import sys
from pathlib import Path

OPS = {"==": "Eq", "!=": "Ne", "<": "Lt", "<=": "Le", ">": "Gt", ">=": "Ge"}


def case_bodies(src):
    """Top-level cases of the tile switch: (labels, body lines without indentation)."""
    start = src.index("private void ApplyTileLight(")
    end = src.index("\n\t}\n", start)
    groups, labels, body = [], [], []
    for raw in src[start:end].split("\n"):
        if re.match(r"^\t\t\tcase \d+:$", raw):
            if body:
                groups.append((labels, body))
                labels, body = [], []
            labels.append(int(raw.strip()[5:-1]))
        elif re.match(r"^\t\t\t(default:|})", raw):
            if labels:
                groups.append((labels, body))
            labels, body = [], []
        elif labels and raw.startswith("\t\t\t\t"):
            body.append(raw.strip())
    return groups


RGB = r"R = (-?[\d.]+)f;\nG = (-?[\d.]+)f;\nB = (-?[\d.]+)f;\n"
COND = r"tile\.frame([XY]) (!=|>=|<=|>|<|==) (\d+)"
NEGATE = {"!=": "==", "==": "!=", ">=": "<", "<": ">=", "<=": ">", ">": "<="}


def rgb(m, i=1):
    return tuple(float(m.group(i + k)) for k in range(3))


def parse(body):
    """(guards, divisor, [(style or None for default, rgb)]) for the simple shapes, else None."""
    text = "\n".join(body) + "\n"
    m = re.fullmatch(RGB + r"break;\n", text)
    if m:
        return [], 0, [(None, rgb(m))]
    m = re.fullmatch(r"if \(((?:" + COND + r"(?: && )?)+)\)\n\{\n" + RGB + r"\}\nbreak;\n", text)
    if m:
        guards = [(f, op, int(v)) for f, op, v in re.findall(COND, m.group(1))]
        return guards, 0, [(None, rgb(m, 5))]
    m = re.fullmatch(r"if \(" + COND + r"\)\n\{\nbreak;\n\}\nswitch \(tile\.frame([XY]) / (\d+)\)\n\{\n(.*)\}\nbreak;\n", text, re.S)
    if m:
        f, op, v, sf, div, inner = m.groups()
        if sf != "Y":
            return None
        styles, pending = [], []
        for part in re.split(r"\n(?=case |default:)", "\n" + inner):
            part = part.strip("\n")
            if not part:
                continue
            labels = re.findall(r"^(?:case (\d+)|(default)):$", part, re.M)
            rest = "\n".join(l for l in part.split("\n") if not re.match(r"^(case \d+|default):$", l)) + "\n"
            pending += [None if d else int(c) for c, d in labels]
            if rest.strip() == "":
                continue
            c = re.fullmatch(RGB + r"break;\n", rest)
            if not c:
                # Animated or random colour: left dark.
                pending = []
                continue
            styles += [(p, rgb(c)) for p in pending]
            pending = []
        return [(f, NEGATE[op], int(v))], int(div), styles
    return None


def torches(src):
    lights = {}
    for m in re.finditer(r"array\[(\d+)\] = new ConstantTorchLight\(([\d.]+)f, ([\d.]+)f, ([\d.]+)f\);", src):
        lights[int(m.group(1))] = tuple(float(m.group(k)) for k in (2, 3, 4))
    return lights


def main():
    src = Path(sys.argv[1])
    scanner = (src / "Terraria.Graphics.Light/TileLightScanner.cs").read_text()
    torch_src = (src / "Terraria.ID/TorchID.cs").read_text()
    lights = torches(torch_src)
    count = int(re.search(r"Count = (\d+);", torch_src).group(1))
    fmt = lambda c: "[" + ", ".join(repr(float(f"{v:.6g}")) for v in c) + "]"
    rules = []
    for labels, body in case_bodies(scanner):
        r = parse(body)
        if r:
            rules += [(t, r) for t in labels]
    rules.sort(key=lambda r: r[0])
    out = [
        "//! Light colours, generated by tools/gen_tile_light.py from the local",
        "//! decompilation of the player's own game. Do not edit by hand.",
        "",
        "use crate::light::{Field::*, Op::*, Rule};",
        "",
        "/// Tile types whose light is fixed or picked by frame, sorted by type.",
        f"pub const RULES: [Rule; {len(rules)}] = [",
    ]
    for t, (guards, div, styles) in rules:
        g = ", ".join(f"({'X' if f == 'X' else 'Y'}, {OPS[op]}, {v})" for f, op, v in guards)
        st = ", ".join(f"({-1 if k is None else k}, {fmt(c)})" for k, c in styles)
        out.append(f"    Rule {{ tile: {t}, guards: &[{g}], div: {div}, styles: &[{st}] }},")
    out += [
        "];",
        "",
        "/// Torch styles with a fixed colour; `None` for the animated ones.",
        f"pub const TORCH: [Option<[f32; 3]>; {count}] = [",
    ]
    out += [f"    Some({fmt(lights[i])})," if i in lights else "    None," for i in range(count)]
    out += ["];", ""]
    open(Path(__file__).parent.parent / "crates/world/src/tile_light.rs", "w").write("\n".join(out))
    print(len(rules), "tile rules,", len(lights), "torches")


if __name__ == "__main__":
    main()
